% ==============================
% Лабораторна робота №4
% Варіант 2
% Дослідження стійкості системи
% ==============================

% Початкова система
num = [2];
den = [5 10 4 8 4 9];

W = tf(num, den);

% Перехідна характеристика початкової системи
figure;
step(W);
grid on;
title('Перехідна характеристика початкової системи');

% Полюси початкової системи
poles = roots(den);
disp('Полюси початкової системи:');
disp(poles);

figure;
pzmap(W);
grid on;
title('Полюси початкової системи');

% Годограф Михайлова початкової системи
w = 0:0.01:10;

U = 9 - 8*w.^2 + 10*w.^4;
V = 4*w - 4*w.^3 + 5*w.^5;

figure;
plot(U, V);
grid on;
xlabel('U(\omega)');
ylabel('V(\omega)');
title('Годограф Михайлова початкової системи');

% ==============================
% Система на межі стійкості
% ==============================

% Новий знаменник після зміни дійсної частини
% комплексно-спряженої пари полюсів на нуль

den_new = [5 15.2047 18.4728 19.6898 9.9806 6.3730];

W_new = tf(num, den_new);

% Перехідна характеристика системи на межі стійкості
figure;
step(W_new);
grid on;
title('Перехідна характеристика системи на межі стійкості');

% Полюси системи на межі стійкості
poles_new = roots(den_new);
disp('Полюси системи на межі стійкості:');
disp(poles_new);

figure;
pzmap(W_new);
grid on;
title('Полюси системи на межі стійкості');

% Годограф Михайлова системи на межі стійкості
U_new = 6.3730 - 19.6898*w.^2 + 15.2047*w.^4;
V_new = 9.9806*w - 18.4728*w.^3 + 5*w.^5;

figure;
plot(U_new, V_new);
grid on;
xlabel('U(\omega)');
ylabel('V(\omega)');
title('Годограф Михайлова системи на межі стійкості');